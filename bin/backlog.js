#!/usr/bin/env node
'use strict';

// Agent-facing backlog CLI.
//
//   node bin/backlog.js                 overview + the recommended next task
//   node bin/backlog.js list [filters]  list tasks (--status --area --severity --ready)
//   node bin/backlog.js next            print the highest-priority ready task brief
//   node bin/backlog.js show <id>       print one task brief
//   node bin/backlog.js set <id> <st>   update status and re-render
//   node bin/backlog.js render          regenerate STATUS.md and tasks/*.md
//   node bin/backlog.js validate        check ids, statuses and dependencies
//
// Statuses: ready | in-progress | blocked | done | wontfix
// Severity order: critical > high > medium > low

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const STORE = path.join(ROOT, 'backlog', 'backlog.json');
const STATUS_FILE = path.join(ROOT, 'backlog', 'STATUS.md');
const TASKS_DIR = path.join(ROOT, 'backlog', 'tasks');

const load = () => JSON.parse(fs.readFileSync(STORE, 'utf8'));
const save = (data) => fs.writeFileSync(STORE, `${JSON.stringify(data, null, 2)}\n`);

function sevRank(sev) {
  return { critical: 0, high: 1, medium: 2, low: 3 }[sev] ?? 9;
}

function isDone(data, id) {
  const t = data.tasks.find((x) => x.id === id);
  return !t || t.status === 'done' || t.status === 'wontfix';
}

function ready(data, task) {
  if (task.status !== 'ready') return false;
  return (task.depends_on || []).every((d) => isDone(data, d));
}

function byPriority(data) {
  return [...data.tasks].sort((a, b) => sevRank(a.severity) - sevRank(b.severity) || a.id.localeCompare(b.id));
}

function nextTask(data) {
  const ordered = byPriority(data);
  return ordered.find((t) => ready(data, t)) || ordered.find((t) => t.status === 'ready') || null;
}

function slug(title) {
  return String(title).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60);
}

function brief(task) {
  const deps = (task.depends_on || []).length ? task.depends_on.join(', ') : 'none';
  const lines = [
    `# ${task.id} — ${task.title}`,
    '',
    `- severity: ${task.severity}`,
    `- area: ${task.area}`,
    `- status: ${task.status}`,
    `- depends_on: ${deps}`,
    `- files: ${(task.files || []).join(', ') || 'n/a'}`,
    `- source: ${task.source || 'n/a'}`,
    '',
    '## Summary',
    task.summary || '',
    '',
    '## Steps',
    ...(task.steps || []).map((s, i) => `${i + 1}. ${s}`),
    '',
    '## Acceptance',
    ...(task.acceptance || []).map((a) => `- ${a}`),
    '',
    '## Tests',
    ...(task.tests || []).map((t) => `- ${t}`),
    '',
  ];
  return lines.join('\n');
}

function parseArgs(args) {
  const flags = {};
  for (let i = 0; i < args.length; i += 1) {
    if (args[i].startsWith('--')) {
      flags[args[i].slice(2)] = args[i + 1] && !args[i + 1].startsWith('--') ? args[++i] : true;
    }
  }
  return flags;
}

function render(data) {
  fs.mkdirSync(TASKS_DIR, { recursive: true });
  for (const t of data.tasks) {
    fs.writeFileSync(path.join(TASKS_DIR, `${t.id}-${slug(t.title)}.md`), `${brief(t)}\n`);
  }
  const rows = byPriority(data).map(
    (t) => `| ${t.id} | ${t.severity} | ${t.area} | ${t.status} | ${(t.depends_on || []).join(', ') || '—'} | ${t.title} |`,
  );
  const counts = {};
  for (const t of data.tasks) counts[t.status] = (counts[t.status] || 0) + 1;
  const summary = Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(' · ');
  const next = nextTask(data);
  const md = [
    '# Vantage backlog',
    '',
    `Updated: ${data.updated || new Date().toISOString().slice(0, 10)} · ${data.tasks.length} tasks · ${summary}`,
    '',
    next ? `**Next up:** \`${next.id}\` — ${next.title} (${next.severity})` : '**Next up:** nothing ready',
    '',
    'Generated by `node bin/backlog.js render`. Edit `backlog.json`, not this file.',
    '',
    '| ID | Sev | Area | Status | Deps | Title |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
  fs.writeFileSync(STATUS_FILE, `${md}\n`);
  return { tasks: data.tasks.length, next };
}

function validate(data) {
  const problems = [];
  const ids = data.tasks.map((t) => t.id);
  const set = new Set(ids);
  if (set.size !== ids.length) problems.push('duplicate ids');
  const statuses = new Set(data.statuses || ['ready', 'in-progress', 'blocked', 'done', 'wontfix']);
  for (const t of data.tasks) {
    if (!statuses.has(t.status)) problems.push(`${t.id}: bad status "${t.status}"`);
    for (const d of t.depends_on || []) if (!set.has(d)) problems.push(`${t.id}: unknown dep ${d}`);
    if (!t.title || !t.severity || !t.area) problems.push(`${t.id}: missing title/severity/area`);
  }
  return problems;
}

(function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const data = load();

  if (cmd === 'list') {
    const flags = parseArgs(rest);
    let tasks = byPriority(data);
    if (flags.status) tasks = tasks.filter((t) => t.status === flags.status);
    if (flags.area) tasks = tasks.filter((t) => t.area === flags.area);
    if (flags.severity) tasks = tasks.filter((t) => t.severity === flags.severity);
    if (flags.ready) tasks = tasks.filter((t) => ready(data, t));
    for (const t of tasks) {
      const mark = ready(data, t) ? ' ' : '*';
      console.log(`${mark} ${t.id}  [${t.severity.padEnd(8)}] ${t.area.padEnd(10)} ${t.status.padEnd(11)} ${t.title}`);
    }
    console.log(`\n${tasks.length} task(s). '*' = blocked by dependencies.`);
    return;
  }

  if (cmd === 'next') {
    const t = nextTask(data);
    if (!t) return console.log('Nothing ready. Run `node bin/backlog.js list`.');
    console.log(brief(t));
    return;
  }

  if (cmd === 'show') {
    const t = data.tasks.find((x) => x.id === rest[0]);
    if (!t) { console.error(`No task ${rest[0]}`); process.exit(1); }
    console.log(brief(t));
    return;
  }

  if (cmd === 'set') {
    const [id, status] = rest;
    const t = data.tasks.find((x) => x.id === id);
    if (!t) { console.error(`No task ${id}`); process.exit(1); }
    if (!(data.statuses || []).includes(status)) { console.error(`Bad status ${status}`); process.exit(1); }
    t.status = status;
    data.updated = new Date().toISOString().slice(0, 10);
    save(data);
    render(data);
    console.log(`${id} → ${status}`);
    return;
  }

  if (cmd === 'render') {
    const info = render(data);
    console.log(`Rendered ${info.tasks} tasks → backlog/STATUS.md and backlog/tasks/`);
    return;
  }

  if (cmd === 'validate') {
    const problems = validate(data);
    if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
    console.log('Backlog OK');
    return;
  }

  // default: overview
  render(data);
  const counts = {};
  for (const t of data.tasks) counts[t.status] = (counts[t.status] || 0) + 1;
  console.log(`Backlog: ${data.tasks.length} tasks (${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')})`);
  const t = nextTask(data);
  console.log(t ? `Next: ${t.id} — ${t.title} (${t.severity})` : 'Next: nothing ready');
  console.log('Use: list | next | show <id> | set <id> <status> | render | validate');
})();
